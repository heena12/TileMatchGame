"""
Regenerates src/services/audio/voiceClips.ts: the spoken praise lines.

    pip install edge-tts imageio-ffmpeg
    python tools/generate_voice_clips.py
    python tools/generate_voice_clips.py --voice en-US-JennyNeural --rate +5% --pitch +4Hz

Each line is synthesised with a neural voice, trimmed of silence, loudness
matched and stored as a small mono WAV (base64), so the game plays the same
clips on web, Android and iOS with no asset pipeline and no internet.

Licensing: `edge-tts` uses Microsoft's online read-aloud service, which is fine
for prototyping. For a store release, replace these clips with audio you have
the rights to use (a paid TTS plan with a commercial licence, or a voice
actor): record WAV files named after the keys below and run this script with
--from-folder <folder>.
"""

import argparse
import asyncio
import base64
import io
import os
import subprocess
import sys
import tempfile
import wave

# key -> spoken text. The key is the text lower-cased, without apostrophes, with
# anything else turned into "-" (see clipKey in ClipVoiceAudio.ts).
LINES = {
    "excellent": "Excellent!",
    "superb-control": "Superb control!",
    "thats-amazing": "That's amazing!",
    "epic-moment": "Epic moment!",
    "awesome": "Awesome!",
    "youre-great": "You're great!",
    "unbelievable": "Unbelievable!",
    "brilliant": "Brilliant!",
}

SAMPLE_RATE = 22050
OUT = os.path.join(
    os.path.dirname(__file__), "..", "src", "services", "audio", "voiceClips.ts"
)

# Trim leading/trailing silence, then match loudness so no line is much louder
# than another, and leave a few milliseconds of tail so nothing is clipped.
FILTER = (
    "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02,"
    "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,areverse,"
    "loudnorm=I=-14:TP=-1.0:LRA=7,"
    "apad=pad_dur=0.04"
)


async def synthesise(text: str, voice: str, rate: str, pitch: str, path: str):
    import edge_tts

    await edge_tts.Communicate(text, voice, rate=rate, pitch=pitch).save(path)


def to_wav(source: str, ffmpeg: str) -> bytes:
    out = source + ".wav"
    subprocess.run(
        [ffmpeg, "-y", "-loglevel", "error", "-i", source, "-af", FILTER,
         "-ar", str(SAMPLE_RATE), "-ac", "1", "-sample_fmt", "s16", out],
        check=True,
    )
    with open(out, "rb") as f:
        return f.read()


def describe(wav: bytes) -> str:
    with wave.open(io.BytesIO(wav)) as w:
        return f"{w.getnframes() / w.getframerate():.2f}s {len(wav) // 1024}KB"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--voice", default="en-US-AriaNeural")
    parser.add_argument("--rate", default="+10%")
    parser.add_argument("--pitch", default="+8Hz")
    parser.add_argument("--from-folder", help="use <key>.wav/.mp3 files from here instead of synthesising")
    args = parser.parse_args()

    import imageio_ffmpeg

    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    clips = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, text in LINES.items():
            if args.from_folder:
                src = next(
                    (os.path.join(args.from_folder, key + ext)
                     for ext in (".wav", ".mp3") if os.path.exists(os.path.join(args.from_folder, key + ext))),
                    None,
                )
                if src is None:
                    print(f"missing {key}.wav/.mp3 in {args.from_folder}", file=sys.stderr)
                    return 1
            else:
                src = os.path.join(tmp, key + ".mp3")
                asyncio.run(synthesise(text, args.voice, args.rate, args.pitch, src))
            wav = to_wav(src, ffmpeg)
            clips[key] = base64.b64encode(wav).decode()
            print(f"{key:15s} {describe(wav)}")

    header = (
        "/**\n"
        " * Spoken praise clips (22 kHz mono WAV, base64) so one voice plays the same on\n"
        " * web, Android and iOS with no asset pipeline. Generated by\n"
        " * tools/generate_voice_clips.py; run it again to change the voice, or point it\n"
        " * at your own recordings with --from-folder.\n"
        " */\n"
        "export const VOICE_CLIPS: Readonly<Record<string, string>> = {\n"
    )
    body = "".join(f"  '{k}':\n    '{v}',\n" for k, v in clips.items())
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + body + "};\n")
    print("wrote", os.path.normpath(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
